/** Linha resumida pra declarar os modelos sem repetir os 4 booleanos toda hora. */
interface Conta {
  codigo: string;
  nome: string;
  grupo: LinhaImportacaoPlanoConta['grupo'];
  sintetica: boolean;
  codigoPai: string | null;
  caixaBanco?: boolean;
  // Só preenchido quando caixaBanco=true -- 'caixa' pra Caixa, 'banco' pra Bancos Conta
  // Movimento. Sem isso, a conta fica marcada "Caixa/Banco" mas sem subtipo, e nunca
  // aparece no select de "Novo caixa"/"Novo banco" (que filtra pelo subtipo exato).
  tipoCaixaBanco?: 'caixa' | 'banco' | 'outra';
  aReceber?: boolean;
  aPagar?: boolean;
}

function linha(c: Conta): LinhaImportacaoPlanoConta {
  return {
    codigo: c.codigo,
    nome: c.nome,
    grupo: c.grupo,
    sintetica: c.sintetica,
    codigoPai: c.codigoPai,
    contaCaixaBanco: c.caixaBanco ?? false,
    tipoCaixaBanco: c.tipoCaixaBanco ?? null,
    contaAReceber: c.aReceber ?? false,
    contaAPagar: c.aPagar ?? false,
  };
}

